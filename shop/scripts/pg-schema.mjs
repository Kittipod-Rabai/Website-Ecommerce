// สร้าง schema ของ PostgreSQL จาก schema หลัก (SQLite) และ (ถ้าระบุชื่อ) สร้าง migration ของ Postgres ให้
//   node scripts/pg-schema.mjs            → อัปเดต prisma/postgres/schema.prisma อย่างเดียว
//   node scripts/pg-schema.mjs <ชื่อ>      → อัปเดต schema + สร้าง migration จากส่วนต่างของ schema เดิม
// หลังแก้ prisma/schema.prisma ทุกครั้ง ให้รัน: npm run db:pg -- add_something
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync, rmSync, readdirSync } from "node:fs";
import path from "node:path";

const dir = "prisma/postgres";
const target = path.join(dir, "schema.prisma");
mkdirSync(path.join(dir, "migrations"), { recursive: true });

const source = readFileSync("prisma/schema.prisma", "utf8");
const pg = [
  "// ไฟล์นี้สร้างอัตโนมัติจาก prisma/schema.prisma ด้วย `npm run db:pg` — ห้ามแก้ด้วยมือ",
  source
    .replace('provider = "sqlite"', 'provider = "postgresql"')
    .replace(/\/\/ Dev uses SQLite[\s\S]*?\/\/ DATABASE_URL to a Postgres URL for production — the schema is portable\.\n/, ""),
].join("\n");

const name = process.argv[2];
if (name) {
  const migDir = path.join(dir, "migrations");
  const hasMigrations = existsSync(migDir) && readdirSync(migDir).some((d) => !d.endsWith(".toml"));
  const oldFile = path.join(dir, ".old.prisma");
  const newFile = path.join(dir, ".new.prisma");
  writeFileSync(newFile, pg);
  const from = hasMigrations && existsSync(target) ? ["--from-schema-datamodel", target] : ["--from-empty"];
  const res = spawnSync("npx", ["prisma", "migrate", "diff", ...from, "--to-schema-datamodel", newFile, "--script"], {
    shell: true,
    encoding: "utf8",
    env: { ...process.env, DATABASE_URL: "postgresql://x:x@localhost:5432/x" },
  });
  rmSync(oldFile, { force: true });
  rmSync(newFile, { force: true });
  if (res.status !== 0) {
    console.error(res.stderr || res.stdout);
    process.exit(1);
  }
  const sql = res.stdout.trim();
  if (!sql || /empty migration/i.test(sql)) {
    console.log("schema ไม่มีการเปลี่ยนแปลง ไม่สร้าง migration");
  } else {
    const stamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
    const out = path.join(migDir, `${stamp}_${name}`);
    mkdirSync(out, { recursive: true });
    writeFileSync(path.join(out, "migration.sql"), sql + "\n");
    writeFileSync(path.join(migDir, "migration_lock.toml"), '# Please do not edit this file manually\nprovider = "postgresql"\n');
    console.log(`สร้าง migration: ${out}`);
  }
}
writeFileSync(target, pg);
console.log(`อัปเดต ${target} แล้ว`);
